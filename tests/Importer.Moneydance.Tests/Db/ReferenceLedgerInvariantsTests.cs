namespace Coffer.Importer.Moneydance.Tests.Db;

/// <summary>
/// Systemic boundary invariants asserted against a full MD import (roadmap #3 —
/// realistic reference ledger + boundary testing). Rather than checking one
/// narrow behavior, this imports an entire ledger through the real pipeline and
/// asserts the ledger-wide invariants whose violation is exactly the class of
/// bug that slipped past shape-poor unit tests (unbalanced headers from the
/// placeholder-price transfer / self-ref `buysellxfr` defects; holdings drifting from their
/// lots after a recompute).
/// </summary>
/// <remarks>
/// Fixture is <c>data/samples/reference-ledger.json</c> — a synthetic, PII-free
/// QIF-origin export (generated by <c>reference-ledger.gen.mjs</c>) carrying the
/// shapes the demo lacks: blank
/// <c>invest.txntype</c> classified via <c>xfer_type</c> + <c>qif_invst_action</c>
/// (the importer's QIF-origin classification path), plus placeholder-price transfers,
/// a self-ref buysellxfr, security diversity (dec 2–9, money-market / mutual /
/// bond / equity), and an inactive position. The invariant battery is
/// fixture-independent — the reusable vehicle.
/// </remarks>
[Collection(DbCollection.Name)]
public sealed class ReferenceLedgerInvariantsTests : DatabaseTest
{
    public ReferenceLedgerInvariantsTests(PostgresFixture fixture, ITestOutputHelper output)
        : base(fixture, output)
    {
    }

    /// <summary>
    /// The five invariants, over EVERY shipped fixture.
    /// </summary>
    /// <remarks>
    /// The battery was always written as fixture-independent — "the reusable
    /// vehicle" — but it only ever ran against one file, so the claim was
    /// untested. The generated Demo carries bank AND investment history, which
    /// is precisely the material these invariants police: a generated buy whose
    /// legs do not balance, or a holding that drifts from its lots after the
    /// recompute, would otherwise ship inside every Demo the hub builds and
    /// the reports slice is built on. Its short span keeps the whole investment
    /// route, so every lot and disposal is here.
    /// </remarks>
    [Theory]
    [MemberData(nameof(Fixtures))]
    public async Task Full_import_satisfies_systemic_invariants(string fixtureFile)
    {
        await using var conn = Db.OpenConnection();
        using var export = Open(fixtureFile);
        var ledgerId = await ImportAsync(conn, export, fixtureFile);

        // Sanity: the fixture actually produced investment holdings to check.
        Assert.True(await conn.ExecuteScalarAsync<int>(
            "SELECT count(*)::int FROM holdings WHERE ledger_id = @L;", new { L = ledgerId }) > 0,
            $"{fixtureFile} produced no holdings to assert against");

        // Invariant 1 — double-entry: every header balances, by the import's own
        // header-balance rule (ADR-0019 / ADR-0053, and ADR-0114 D13's two-amount
        // pairs), so this battery and the import cannot hold two rules. The
        // placeholder-price + self-ref transfer bugs violated this.
        var balance = (await new ImportValidator(conn).ValidateAsync(ledgerId))
            .Checks.Single(c => c.Name == "header-balance");
        Assert.True(balance.Passed, "unbalanced headers: " + balance.Message);

        // Invariant 2 — holdings reconcile with their lots: quantity = Σ open-lot
        // quantity and cost_basis = Σ open-lot cost (both split-adjusted by the
        // recompute). A drift here means recompute produced a holding its own
        // lots don't support.
        var drifted = await conn.QueryAsync<(Guid Id, decimal Q, decimal LotQ, decimal CB, decimal LotCB)>(
            """
            SELECT h.id, h.quantity, COALESCE(SUM(l.quantity), 0) AS lot_q,
                   h.cost_basis, COALESCE(SUM(l.quantity * l.unit_cost), 0) AS lot_cb
              FROM holdings h
              LEFT JOIN lots l ON l.holding_id = h.id AND l.is_closed = FALSE
             WHERE h.ledger_id = @L
             GROUP BY h.id, h.quantity, h.cost_basis
            HAVING abs(h.quantity   - COALESCE(SUM(l.quantity), 0)) > 0.0001
                OR abs(h.cost_basis - COALESCE(SUM(l.quantity * l.unit_cost), 0)) > 0.01;
            """, new { L = ledgerId });
        Assert.True(!drifted.Any(),
            "holdings not reconciled with lots: " + string.Join(", ",
                drifted.Select(d => $"{d.Id} qty {d.Q}/{d.LotQ} basis {d.CB}/{d.LotCB}")));

        // Invariant 3 — realized_gains only ever attach to a disposal (a
        // negative-quantity holdings leg), never an acquisition.
        var badRealized = await conn.ExecuteScalarAsync<int>(
            """
            SELECT count(*)::int
              FROM realized_gains rg
              JOIN txn_legs l ON l.id = rg.sell_leg_id
             WHERE rg.ledger_id = @L AND NOT (l.quantity IS NOT NULL AND l.quantity < 0);
            """, new { L = ledgerId });
        Assert.Equal(0, badRealized);

        // Invariant 4 — no holding is left negative (oversold), a classic
        // import-ordering / merge defect.
        Assert.Equal(0, await conn.ExecuteScalarAsync<int>(
            "SELECT count(*)::int FROM holdings WHERE ledger_id = @L AND quantity < -0.0001;",
            new { L = ledgerId }));

        // Invariant 5 — the memo-and-tags placement (ADR-0108 D1, D13): no notes on a one-posting
        // header, nothing on an event's investment side, no blank memo.
        Assert.Empty(await Coffer.Api.Tests.Integration.Infra.MemoPlacementInvariants.ViolationsAsync(conn, ledgerId));
    }

    /// <summary>
    /// What the reference ledger exists FOR, which the demo deliberately does
    /// not duplicate: the QIF-origin classification (blank
    /// <c>invest.txntype</c>, resolved via <c>xfer_type</c> +
    /// <c>qif_invst_action</c>) and security diversity across decimal
    /// precisions. Those shapes are pathological on purpose and must never
    /// migrate into the ledger a new user explores — which is why this stays a
    /// separate fixture rather than being folded into the demo.
    /// </summary>
    [Fact]
    public async Task Reference_ledger_still_spans_the_shapes_it_exists_for()
    {
        await using var conn = Db.OpenConnection();
        using var export = Open(ReferenceLedger);
        var ledgerId = await ImportAsync(conn, export, ReferenceLedger);

        var actions = (await conn.QueryAsync<string>(
            "SELECT DISTINCT action FROM txn_headers WHERE ledger_id = @L AND action IS NOT NULL;",
            new { L = ledgerId })).ToHashSet();
        foreach (var required in new[] { "buy", "sell", "buyx", "sellx", "dividend_cash", "dividend_reinvest", "misc" })
            Assert.True(actions.Contains(required), $"reference ledger missing shape: {required} (have: {string.Join(",", actions)})");
        Assert.True(await conn.ExecuteScalarAsync<int>(
            "SELECT count(*)::int FROM securities WHERE ledger_id = @L;", new { L = ledgerId }) >= 5,
            "reference ledger should span multiple securities");

        // Security diversity reaches the classification: each security's type comes
        // from its type-s account in Moneydance's numeric codes (ADR-0016, amendment
        // of 2026-11-18), so the bond is a bond and the money-market fund is cash.
        var vehicles = (await conn.QueryAsync<(string Ticker, string? AssetClass, string? VehicleType)>(
            "SELECT ticker, asset_class, vehicle_type FROM securities WHERE ledger_id = @L;",
            new { L = ledgerId }))
            .ToDictionary(r => r.Ticker, r => (r.AssetClass, r.VehicleType));
        Assert.Equal(("fixed_income", "bond"), vehicles["BND"]);
        Assert.Equal(("cash", "money_market"), vehicles["MMF"]);
        Assert.Equal(((string?)null, "etf"), vehicles["ETF"]);
        Assert.Equal(((string?)null, "mutual_fund"), vehicles["MFA"]);
    }

    private const string ReferenceLedger = "reference-ledger.json";
    private const string GeneratedDemoShort = "generated Demo, short span";

    /// <summary>The committed reference ledger and the generated Demo's short span.</summary>
    public static TheoryData<string> Fixtures() => new() { ReferenceLedger, GeneratedDemoShort };

    private static MdExport Open(string fixture) =>
        fixture == GeneratedDemoShort
            ? DemoTestExports.ShortExport()
            : MdItemReader.ReadFile(LocateSampleFile(fixture));

    /// <summary>
    /// Import an export through the real pipeline steps (the path a live import
    /// runs, so import-layer defects surface here).
    /// </summary>
    private static async Task<Guid> ImportAsync(NpgsqlConnection conn, MdExport export, string fixtureName)
    {
        var ledgerId = await ProvisionLedgerAsync(conn);
        var ctx = new ImportContext(export, ledgerId);
        var src = "test:" + fixtureName;

        await SecurityImportStep.RunAsync(conn, ctx);
        await AccountImportStep.RunAsync(conn, ctx);
        await SecuritySplitImportStep.RunAsync(conn, ctx);
        await TransactionImportStep.RunAsync(conn, ctx, src);
        await InvestmentTransactionImportStep.RunAsync(conn, ctx, src);
        await BalanceRecomputeStep.RunAsync(conn, ctx, default);
        await StoredNotesSeed.ComputeImportedNotesAsync(conn, ledgerId);
        return ledgerId;
    }

    private static async Task<Guid> ProvisionLedgerAsync(NpgsqlConnection conn)
    {
        if (await conn.ExecuteScalarAsync<Guid?>("SELECT id FROM ledgers WHERE id=@Id;", new { Id = TestLedger.Id }) is null)
            await conn.ExecuteAsync("INSERT INTO ledgers (id, name) VALUES (@Id,'Default');", new { Id = TestLedger.Id });
        return TestLedger.Id;
    }

    private static string LocateSampleFile(string fixtureFile)
    {
        var cur = new DirectoryInfo(AppContext.BaseDirectory);
        while (cur is not null)
        {
            var p = Path.Combine(cur.FullName, "data", "samples", fixtureFile);
            if (File.Exists(p)) return p;
            cur = cur.Parent;
        }
        throw new FileNotFoundException($"Could not locate {fixtureFile} from " + AppContext.BaseDirectory);
    }
}
