#!/usr/bin/env node
// =============================================================================
// starter-categories.gen.mjs — derive the starter category tree from the demo
// sample, so a new ledger and the Demo ledger cannot disagree (ADR-0091).
// =============================================================================
//
// Before this existed the two paths had different taxonomies: a new ledger got a
// hand-written 61-entry `starter-categories.json`, while Demo inherited whatever
// `moneydance-export-demo.json` happened to contain (108). Only ~6 of ~22
// top-level names overlapped, so "the categories I saw in Demo" and "the
// categories my own ledger has" were unrelated sets.
//
// The demo export is now the single source of truth: it carries the curated
// Moneydance-derived tree, and this script projects it into the shape the API's
// StarterCategoriesSeeder embeds. Regenerate after editing the export:
//
//     node data/samples/starter-categories.gen.mjs
//
// Verifies (and fails loudly) rather than trusting:
//   * every category has a kind of income or expense
//   * nesting is at most parent -> child (the seeder models one level)
//   * no duplicate name WITHIN a kind + parent (a name may legitimately appear
//     under both kinds — "Investment" is an expense parent for Trading
//     Commission AND an income parent for Dividends; that is correct modelling,
//     not a duplicate)
// =============================================================================

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const exportPath = join(here, 'moneydance-export-demo.json');
const outPath = join(here, '..', '..', 'src', 'Api', 'Provisioning', 'starter-categories.json');

const die = (msg) => {
    console.error(`starter-categories.gen: ${msg}`);
    process.exit(1);
};

const md = JSON.parse(readFileSync(exportPath, 'utf8'));

// Moneydance account types: 'i' income, 'e' expense. Everything else (bank,
// investment, security, …) is a real account, not a category.
const KIND = { i: 'income', e: 'expense' };
const accounts = md.all_items.filter((x) => x.obj_type === 'acct');
const byId = new Map(accounts.map((a) => [a.id, a]));
const categories = accounts.filter((a) => KIND[a.type]);

if (categories.length === 0) die('no income/expense accounts found — wrong export shape?');

// Roots have no parent, or a parent that is not itself a category (MD hangs the
// top level off a root account).
const isCategory = (id) => id && KIND[(byId.get(id) || {}).type];
const roots = categories.filter((c) => !isCategory(c.parentid));
const childrenOf = (id) => categories.filter((c) => c.parentid === id);

// Depth guard: the seeder models parent -> child only.
for (const root of roots) {
    for (const child of childrenOf(root.id)) {
        const grandkids = childrenOf(child.id);
        if (grandkids.length > 0) {
            die(
                `"${root.name} > ${child.name}" has grandchildren ` +
                `(${grandkids.map((g) => g.name).join(', ')}); the starter seeder is one level deep`,
            );
        }
    }
}

const tree = roots
    .map((root) => {
        const kids = childrenOf(root.id).map((c) => c.name).sort((a, b) => a.localeCompare(b));
        const node = { name: root.name, kind: KIND[root.type] };
        if (kids.length) node.children = kids;
        return node;
    })
    // income first, then expense; alphabetical within each — stable output so a
    // regeneration produces a reviewable diff rather than a reshuffle.
    .sort((a, b) =>
        a.kind === b.kind ? a.name.localeCompare(b.name) : a.kind === 'income' ? -1 : 1,
    );

// Duplicate check, scoped per kind (see header note about "Investment").
for (const kind of ['income', 'expense']) {
    const names = tree.filter((t) => t.kind === kind).map((t) => t.name);
    const dupes = names.filter((n, i) => names.indexOf(n) !== i);
    if (dupes.length) die(`duplicate top-level ${kind} categories: ${[...new Set(dupes)].join(', ')}`);
    for (const node of tree.filter((t) => t.kind === kind && t.children)) {
        const dup = node.children.filter((n, i) => node.children.indexOf(n) !== i);
        if (dup.length) die(`duplicate children under ${kind} "${node.name}": ${dup.join(', ')}`);
    }
}

const total = tree.length + tree.reduce((n, t) => n + (t.children?.length ?? 0), 0);

const payload = {
    '//':
        'GENERATED by data/samples/starter-categories.gen.mjs from ' +
        'data/samples/moneydance-export-demo.json — do not hand-edit. The demo export is the ' +
        'single source of truth so a new ledger and the Demo ledger get the SAME categories ' +
        '(ADR-0091). Children inherit the parent kind. Seeded on the empty-new-ledger paths; ' +
        'the Demo path gets these same categories via the import instead.',
    categories: tree,
};

writeFileSync(outPath, JSON.stringify(payload, null, 2) + '\n', 'utf8');
console.log(
    `starter-categories.gen: wrote ${total} categories ` +
    `(${tree.length} top-level, ${total - tree.length} children) to ${outPath}`,
);
