using Microsoft.AspNetCore.Mvc;

using Coffer.Api.Auth;
using Coffer.Api.Db.Repositories;
using Coffer.Api.Errors;
using Coffer.Api.Import;
using Coffer.Api.Provisioning;
using Coffer.Api.Provisioning.Demo;
using Coffer.Api.Provisioning.DemoSeeding;
using Coffer.Importer.Moneydance.Pipeline;

namespace Coffer.Api.Endpoints;

/// <summary>
/// The hub's Demo ledger (ADR-0115 D2, D3), on the <c>/api/ledgers</c> group: add a Demo,
/// and find its build again. Any authenticated user may add one, on every install.
/// </summary>
/// <remarks>
/// <para>A Demo is generated for the caller's today, then imported as an ordinary
/// background Moneydance import, under the same limits as an upload: one running import
/// per user, and one parsed export in memory install-wide. Both refusals are
/// <c>import-already-running</c>, as for an upload.</para>
/// <para>Each Demo is a new ledger, named by <see cref="DemoLedgerName.Next"/> from the
/// caller's visible ledgers. A failed build keeps nothing, so trying again takes the
/// same name.</para>
/// <para>Every refusal after the name is chosen carries it as a <c>ledgerName</c>
/// extension, so the hub can say which build failed. The busy refusals come before the
/// name, and say only that another import is running.</para>
/// </remarks>
internal static class DemoLedgerEndpoints
{
    /// <summary>
    /// <c>POST /api/ledgers/demo?today=yyyy-MM-dd</c> — start building a new Demo that
    /// ends on <paramref name="today"/>, the caller's local date. Without it the Demo ends
    /// on the server's UTC date, the register's own fallback.
    /// <para>200: the running job, as <see cref="DemoJobResponse"/>. 422:
    /// <c>import-already-running</c>, <c>demo-date-in-future</c>,
    /// <c>import-parse-failed</c> (the server lacks the memory to read it). 500: the
    /// Demo could not be generated or read.</para>
    /// </summary>
    internal static async Task<IResult> StartAsync(
        [FromQuery] DateOnly? today,
        ICurrentUserAccessor currentUser,
        LedgersRepository ledgers,
        ImportJobRunner runner,
        ImportJobRegistry registry,
        ImportMemoryGate gate,
        [FromServices] Func<DateOnly, DemoSpec> specFactory,
        TimeProvider clock,
        ILoggerFactory loggerFactory,
        CancellationToken cancellationToken)
    {
        // The register's rule for "today", so the Demo's last day is never Scheduled.
        var serverToday = ScheduledBoundary.Today(null, clock);
        if (today is { } sent && sent > serverToday.AddDays(1))
            return BusinessError.Problem(BusinessError.Codes.DemoDateInFuture,
                "The Demo ends on this computer's date, and that date is more than a day after the "
                + "server's. Check the computer's clock, then try again.");
        var asOf = ScheduledBoundary.Today(today, clock);

        // Refused before the gate, so a press while the caller's own import runs never
        // generates and parses a Demo under the install-wide slot only to be refused by
        // the runner. The runner's check below stays the authority.
        if (registry.HasRunning(currentUser.UserId)) return AlreadyRunning();

        // Generated and parsed under the gate an upload is parsed under: the Demo is a
        // full export, and only one is held in memory at a time.
        var slot = gate.TryEnter();
        if (slot is null) return ImportEndpoints.Busy();

        string? name = null;
        try
        {
            var visible = await ledgers.GetVisibleAsync(currentUser.UserId, cancellationToken)
                .ConfigureAwait(false);
            name = DemoLedgerName.Next(visible.Select(l => l.Name));

            var build = DemoExportGenerator.Generate(specFactory(asOf));

            // The check an upload gets before its parse, on the generated bytes.
            var budget = GC.GetGCMemoryInfo().TotalAvailableMemoryBytes;
            if (ImportEndpoints.EstimatedParseBytes(build.Json.Length) > budget)
            {
                // The hub shows its fixed failed-build sentence, which points here.
                var detail = ImportEndpoints.NotEnoughMemoryDetail(build.Json.Length, budget);
                loggerFactory.CreateLogger("Coffer.Api.Provisioning")
                    .LogWarning("Building {LedgerName} was refused: {Detail}", name, detail);
                return BusinessError.Problem(BusinessError.Codes.ImportParseFailed,
                    detail, title: null, NameExtension(name));
            }

            var export = build.ToExport();

            // Ownership of the parsed export and its memory slot passes to the runner,
            // which releases both on every path, the refused one included.
            var owned = slot;
            slot = null;
            var jobId = runner.Start(currentUser.UserId, name, export, owned,
                demo: new DemoJobInput(build.Manifest, build.CardStatementCsv, asOf));
            if (jobId is null) return AlreadyRunning();

            // Read back from the registry, so the first answer already counts every step.
            var job = registry.Snapshot(jobId.Value)
                ?? throw new InvalidOperationException($"Demo job {jobId} is not in the registry it was started in.");
            return Results.Ok(ToDemoJobDto(job));
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            loggerFactory.CreateLogger("Coffer.Api.Provisioning")
                .LogError(ex, "Starting a Demo ledger failed for user {UserId}.", currentUser.UserId);
            return Results.Problem(
                statusCode: StatusCodes.Status500InternalServerError,
                title: "The Demo could not be started",
                detail: name is null
                    ? "The Demo could not be started. Try again, or check the server logs."
                    : ImportJobRunner.DemoFailedError(name),
                extensions: name is null ? null : NameExtension(name));
        }
        finally
        {
            slot?.Dispose();
        }
    }

    /// <summary>
    /// <c>GET /api/ledgers/demo/job</c> — the caller's Demo job, running or finished, as
    /// <see cref="DemoJobResponse"/>; 204 when there is none. It is gone once the caller
    /// starts another import or the server restarts.
    /// </summary>
    internal static IResult GetJob(ICurrentUserAccessor currentUser, ImportJobRegistry registry) =>
        registry.LatestDemo(currentUser.UserId) is { } job
            ? Results.Ok(ToDemoJobDto(job))
            : Results.NoContent();

    private static IResult AlreadyRunning() =>
        BusinessError.Problem(BusinessError.Codes.ImportAlreadyRunning,
            "An import is already running. Wait for it to finish before starting another.");

    private static Dictionary<string, object?> NameExtension(string name) => new() { ["ledgerName"] = name };

    /// <summary>A Demo job as the hub reads it: the import job's fields, plus its name,
    /// phase, and the step in progress with its label.</summary>
    internal static DemoJobResponse ToDemoJobDto(ImportJob job)
    {
        var dto = ImportEndpoints.ToJobDto(job);
        var running = job.State == ImportJobState.Running;
        // The import reports a step once it is done, so the one in progress is the next.
        var stepNumber = running ? Math.Min(job.Completed + 1, job.Total) : job.Total;
        return new DemoJobResponse(
            dto.JobId, dto.State, dto.Completed, dto.Total, dto.Step, dto.LedgerId, dto.Error,
            dto.Warnings, dto.SkippedTransactions, dto.SkippedTransactionsNotListed,
            LedgerName: job.LedgerName,
            Phase: job.Phase == ImportJobPhase.Examples ? "examples" : "import",
            StepNumber: stepNumber,
            StepLabel: running ? DemoProgressLabels.ForStep(stepNumber) : null);
    }

    /// <summary>
    /// A Demo job's status: the fields of an import job's status, plus what the hub shows.
    /// </summary>
    /// <param name="LedgerName">The Demo's name, chosen when it was started.</param>
    /// <param name="Phase"><c>import</c> until the import commits, then <c>examples</c>.</param>
    /// <param name="StepNumber">The step in progress, counted from 1, while the job runs;
    /// <see cref="Total"/> once it has finished.</param>
    /// <param name="StepLabel">The readable label of the step in progress while the job
    /// runs; null once it has finished, when no step is.</param>
    internal sealed record DemoJobResponse(
        string JobId, string State, int Completed, int Total, string? Step, string? LedgerId, string? Error,
        IReadOnlyList<ImportWarning> Warnings,
        IReadOnlyList<ImportSkippedTransaction> SkippedTransactions,
        int SkippedTransactionsNotListed,
        string LedgerName,
        string Phase,
        int StepNumber,
        string? StepLabel);
}
